import { g } from 'genshin-ts/runtime/core'
import { int } from 'genshin-ts/runtime/value'
import { Signal } from './signals.js'

/** 隐藏收集物总数（与 gen-maze.py 产出的「隐藏_*」实体数一致；编译期常量） */
const TOTAL = 4n

/**
 * T12 复现 · 《空中花园》式迷宫 —— 隐藏收集物「计数与集齐」中心图（图 id 1073741826）
 *
 * ## 为什么单独一张图
 *
 * `maze-collect.ts` 必须在 4 个带选项卡的实体上各挂一份（事件只发给 tabBar 所在实体的图），
 * 而**节点图变量不跨实例**——那份图不能持有共享计数。
 * 本图**只挂 1 份**（挂普通实体），它持有唯一的 `已收集数`，收 4 份信号后判定集齐。
 *
 * 架构：4 × 无状态拾取图 --(信号 T12隐藏物已拾取)--> 1 × 计数图
 *
 * ## 设计依据（逐条对应 docs/knowledge-graph/reproduction/T12-design.md）
 *   决策 4：正常走出 = 正常通关；拿齐全部收集物 = 额外回馈
 *   决策 5：**不用动态文字**告诉玩家"有几个隐藏"——改用空间布局（几何层已落地）
 *   决策 8：不设单向门，本图不做任何封锁
 *   原设计的"集齐后发信号触发场景惊喜"因 R13（信号编译期强前置）曾暂缓，现已随本信号一并恢复。
 *
 * ## 挂载目标（红线）
 *   挂**普通场景实体**。⚠️ **严禁挂关卡实体 1094713345**——技能红线：挂它致游戏报「地图异常」无法启动。
 */
g.server({
  id: 1073741826,
  variables: {
    /** 已收集数量：本图单实例，故该变量是全局唯一计数 */
    已收集数: new int(0),
    /** 集齐后置真（幂等标记，供后续接场景回馈时判重） */
    已集齐: false
  }
}).onSignal(Signal.T12隐藏物已拾取, (evt, f) => {
  // ① 累加。信号参数 `序号` 当前仅作回执用途（4 个隐藏物各只有 1 个选项，tabId 恒为 1），
  //    故计数以「收到几次信号」为准而非按序号去重。
  const collected = f.get('已收集数') + 1n
  f.set('已收集数', collected)

  // ② 集齐判定（TOTAL 与 gen-maze.py 产出的「隐藏_*」实体数一致）
  if (collected >= TOTAL) {
    f.set('已集齐', true)
  }
})
