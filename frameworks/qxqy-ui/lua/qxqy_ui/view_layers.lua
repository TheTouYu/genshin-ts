  `docs/ui-tutorial/official-ui-tutorial.md:1019`：
    层级越大越靠上；**同层级的会按照创建时序排列，后创建的在上**。
  两种渲染模式（同文件 :1005-1023）：
    · 【时序渲染(旧)】只看创建时序，**层级参数不生效**（月之六前存档默认）；
    · 【层级渲染(新)】按层级配置渲染，同层回落到创建时序（月之六后新建存档默认）。
  **用户 2026-11-02 确认本图用的是「层级渲染(新)」** ⇒ 层级值生效。
  ⚠ 但 Lua 侧**没有设置层级值的 API**（`Lua客户端UI脚本API` 的 ClientUIBaseControl 字段表
