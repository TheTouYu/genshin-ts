/**
 * ui/tests/extract-queue-donors.ts — 从真实编辑器快照提取队列样式成员 donor（票10）
 *
 * 用法：npx tsx ui/tests/extract-queue-donors.ts
 * donor 选点：队列样式素材成员与按钮素材成员内部常量不同（几何/缩放 1.0 vs 0.9）——
 *   - queue-member-image 轮53 1073742134 595B f504=组2133（队列图片成员，t38 源=官方 101078）
 *   - queue-member-text  轮54 1073742136 616B f504=组2135（队列文本成员）
 * 组记录复用 material-member 的 group-create（同「默认状态素材组」创建形态）。
 */

import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

import { parseRoot9 } from '../src/record.js'
import type { QueueMemberDonor } from '../src/queue-donors.js'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const FIXTURES = path.join(ROOT, '.gsts', 'diff-exp', 'ui学习')
const DONORS_FILE = path.join(ROOT, 'ui', 'src', 'queue-donors.ts')

const SOURCES = [
  {
    id: 'queue-group' as const,
    snapshot: '1073741909.after-重启53-队列项样式图片-c23fef5c.gil',
    recordId: 1073742133,
    expectLen: 646,
    expectParent: null,
    expectKind: 'asset'
  },
  {
    id: 'queue-member-image' as const,
    snapshot: '1073741909.after-重启53-队列项样式图片-c23fef5c.gil',
    recordId: 1073742134,
    expectLen: 595,
    expectParent: 1073742133,
    expectKind: 'image'
  },
  {
    id: 'queue-member-text' as const,
    snapshot: '1073741909.after-重启54-队列样式2-2a260b6c.gil',
    recordId: 1073742136,
    expectLen: 616,
    expectParent: 1073742135,
    expectKind: 'textbox'
  }
]

if (!fs.existsSync(FIXTURES)) {
  console.log('SKIP: .gsts/diff-exp/ui学习/ 不存在')
  process.exit(0)
}

function extract(): QueueMemberDonor[] {
  const donors: QueueMemberDonor[] = []
  for (const s of SOURCES) {
    const parsed = parseRoot9(new Uint8Array(fs.readFileSync(path.join(FIXTURES, s.snapshot))))
    const r = parsed.recordsById.get(s.recordId)
    assert.ok(r, `记录 ${s.recordId} 不存在`)
    assert.equal(r.kind, s.expectKind, `kind=${r.kind}`)
    assert.equal(r.parentId, s.expectParent, 'parent 漂移')
    assert.equal(r.raw.length, s.expectLen, `长度 ${r.raw.length} != ${s.expectLen}`)
    donors.push({
      id: s.id,
      sourceSnapshot: s.snapshot,
      selfId: s.recordId,
      parentId: r.parentId,
      sha256: crypto.createHash('sha256').update(Buffer.from(r.raw)).digest('hex'),
      hex: Buffer.from(r.raw).toString('hex')
    })
    console.log(`extracted ${s.id}: record=${s.recordId} len=${r.raw.length}`)
  }
  return donors
}

function render(donors: QueueMemberDonor[]): string {
  const literal = donors
    .map(
      (d) =>
        `  {\n    id: '${d.id}',\n    sourceSnapshot: '${d.sourceSnapshot}',\n    selfId: ${d.selfId},\n    parentId: ${d.parentId},\n    sha256: '${d.sha256}',\n    hex:\n      '${d.hex}'\n  }`
    )
    .join(',\n')
  return `/**
 * ui/src/queue-donors.ts — 队列样式素材成员 donor 注册表（票10）
 *
 * ⚠️ AUTO-GENERATED by \`npx tsx ui/tests/extract-queue-donors.ts\` —— 勿手改。
 * 队列样式成员与按钮素材成员内部常量不同（几何/缩放 1.0）——独立 donor：
 *   - queue-member-image：轮53（595B，t38 源=官方 101078）
 *   - queue-member-text：轮54（616B，字号 30/文本可参数化改写）
 * 组记录复用 material-member-donors 的 group-create（同创建形态）。
 */

export type QueueMemberDonorId = 'queue-group' | 'queue-member-image' | 'queue-member-text'

export interface QueueMemberDonor {
  id: QueueMemberDonorId
  sourceSnapshot: string
  selfId: number
  parentId: number | null
  sha256: string
  hex: string
}

export const QUEUE_MEMBER_DONORS: QueueMemberDonor[] = [
${literal}
]

export function queueMemberDonor(id: QueueMemberDonorId): QueueMemberDonor {
  const donor = QUEUE_MEMBER_DONORS.find((item) => item.id === id)
  if (!donor) {
    throw new Error(\`[error] queue member donor 缺失（\${id}）：先运行 npx tsx ui/tests/extract-queue-donors.ts\`)
  }
  return donor
}
`
}

const donors = extract()
fs.writeFileSync(DONORS_FILE, render(donors))
console.log(`wrote ${DONORS_FILE}`)
