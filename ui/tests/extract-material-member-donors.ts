/**
 * ui/tests/extract-material-member-donors.ts — 从真实编辑器快照提取素材成员 donor（票10）
 *
 * 用法：npx tsx ui/tests/extract-material-member-donors.ts
 * donor 选点（references/ui-controls.md）：
 *   - group-create  轮16  1073742070  646B  parentless「按下状态素材组」（创建形态，f503 含成员 1073742071）
 *   - member-text   轮15  1073742069  616B  f504=组 2044（悬浮状态文本框成员）
 *   - member-image  轮16  1073742071  595B  f504=组 2070（图片成员，官方静态资源 101078）
 */

import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

import { parseRoot9 } from '../src/record.js'
import type { MaterialMemberDonor } from '../src/material-member-donors.js'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const FIXTURES = path.join(ROOT, '.gsts', 'diff-exp', 'ui学习')
const DONORS_FILE = path.join(ROOT, 'ui', 'src', 'material-member-donors.ts')

const DONOR_SOURCES = [
  {
    id: 'group-create' as const,
    snapshot: '1073741909.after-重启16-按下图片素材-e2afd1ad.gil',
    recordId: 1073742070,
    expectLen: 646,
    expectParent: null,
    expectKind: 'asset'
  },
  {
    id: 'member-text' as const,
    snapshot: '1073741909.after-重启15-悬浮射击文本-951e07ad.gil',
    recordId: 1073742069,
    expectLen: 616,
    expectParent: 1073742044,
    expectKind: 'textbox'
  },
  {
    id: 'member-image' as const,
    snapshot: '1073741909.after-重启16-按下图片素材-e2afd1ad.gil',
    recordId: 1073742071,
    expectLen: 595,
    expectParent: 1073742070,
    expectKind: 'image'
  }
]

if (!fs.existsSync(FIXTURES)) {
  console.log('SKIP: .gsts/diff-exp/ui学习/ 不存在')
  process.exit(0)
}

function extract(): MaterialMemberDonor[] {
  const donors: MaterialMemberDonor[] = []
  for (const source of DONOR_SOURCES) {
    const gilPath = path.join(FIXTURES, source.snapshot)
    assert.ok(fs.existsSync(gilPath), `快照缺失: ${source.snapshot}`)
    const parsed = parseRoot9(new Uint8Array(fs.readFileSync(gilPath)))
    const record = parsed.recordsById.get(source.recordId)
    assert.ok(record, `记录 ${source.recordId} 不存在于 ${source.snapshot}`)
    assert.equal(record.kind, source.expectKind, `kind=${record.kind} != ${source.expectKind}`)
    assert.equal(record.parentId, source.expectParent, 'parent 漂移')
    assert.equal(record.raw.length, source.expectLen, `长度 ${record.raw.length} != ${source.expectLen}`)
    donors.push({
      id: source.id,
      sourceSnapshot: source.snapshot,
      selfId: source.recordId,
      parentId: record.parentId,
      sha256: crypto.createHash('sha256').update(Buffer.from(record.raw)).digest('hex'),
      hex: Buffer.from(record.raw).toString('hex')
    })
    console.log(`extracted ${source.id}: record=${source.recordId} len=${record.raw.length}`)
  }
  return donors
}

function render(donors: MaterialMemberDonor[]): string {
  const donorsLiteral = donors
    .map(
      (d) =>
        `  {\n` +
        `    id: '${d.id}',\n` +
        `    sourceSnapshot: '${d.sourceSnapshot}',\n` +
        `    selfId: ${d.selfId},\n` +
        `    parentId: ${d.parentId === null ? 'null' : d.parentId},\n` +
        `    sha256: '${d.sha256}',\n` +
        `    hex:\n` +
        `      '${d.hex}'\n` +
        `  }`
    )
    .join(',\n')
  return `/**
 * ui/src/material-member-donors.ts — 素材成员命令的字节级 donor 注册表（票10）
 *
 * ⚠️ AUTO-GENERATED by \`npx tsx ui/tests/extract-material-member-donors.ts\` —— 勿手改。
 * 字节来源 = 真实编辑器快照（.gsts/diff-exp/ui学习/）：
 *   - group-create：轮16（按下状态直接加图片素材 →「按下状态素材组」646B 创建形态，
 *     comps [15,12,23,56]，f503 含单成员；其它状态经组名改写派生）
 *   - member-text：轮15（悬浮状态组添加文本框素材 616B，f504=组；文本/颜色可参数化改写）
 *   - member-image：轮16（图片成员 595B，f504=组；t38 源=官方静态资源 101078）
 * 字节级同步核验见 ui/tests/material-member-assert.ts（轮14→15 / 轮15→16 重放）。
 */

export type MaterialMemberDonorId = 'group-create' | 'member-text' | 'member-image'

export interface MaterialMemberDonor {
  id: MaterialMemberDonorId
  /** 提取来源快照文件名 */
  sourceSnapshot: string
  selfId: number
  parentId: number | null
  /** 记录原始字节 sha256（防漂移） */
  sha256: string
  /** 记录原始字节 hex */
  hex: string
}

/** 提取脚本覆写点（空数组=占位态 fail-closed） */
export const MATERIAL_MEMBER_DONORS: MaterialMemberDonor[] = [
${donorsLiteral}
]

export function materialMemberDonor(id: MaterialMemberDonorId): MaterialMemberDonor {
  const donor = MATERIAL_MEMBER_DONORS.find((item) => item.id === id)
  if (!donor) {
    throw new Error(
      \`[error] material-member donor 缺失（\${id}）：先运行 npx tsx ui/tests/extract-material-member-donors.ts；\` +
        '缺失时禁止凭空猜字节（fail-closed）'
    )
  }
  return donor
}
`
}

const donors = extract()
assert.equal(donors.length, DONOR_SOURCES.length)
fs.writeFileSync(DONORS_FILE, render(donors))
console.log(`wrote ${DONORS_FILE}`)
