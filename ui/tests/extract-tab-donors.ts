/**
 * ui/tests/extract-tab-donors.ts — 从真实编辑器快照提取页签 donor 字节（票10）
 *
 * 用法：npx tsx ui/tests/extract-tab-donors.ts
 * donor 选点（references/ui-controls.md；取该动作首次新建事件的原始字节）：
 *   - tab-create  轮29  1073742097  1103B  f504=固有容器 2084（页签全默认：
 *     单页面项「页签项_1」+ 页签文本 + 默认选择哨兵 + 空 f503/f504 状态块）
 * 缺快照目录时 SKIP（与 exhaustive-snapshot-verify.ts 同一约定）。
 */

import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

import { parseRoot9 } from '../src/record.js'
import type { TabDonor } from '../src/tab-donors.js'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const FIXTURES = path.join(ROOT, '.gsts', 'diff-exp', 'ui学习')
const DONORS_FILE = path.join(ROOT, 'ui', 'src', 'tab-donors.ts')

const DONOR_SOURCES = [
  {
    id: 'tab-create' as const,
    snapshot: '1073741909.after-重启29-悬浮页加页签-de3ffb3f.gil',
    recordId: 1073742097,
    expectLen: 1103,
    expectParent: 1073742084,
    expectKind: 'tab'
  }
]

if (!fs.existsSync(FIXTURES)) {
  console.log('SKIP: .gsts/diff-exp/ui学习/ 不存在（本地快照核验需真实差分留存）')
  process.exit(0)
}

function sha256(bytes: Uint8Array): string {
  return crypto.createHash('sha256').update(Buffer.from(bytes)).digest('hex')
}

function extract(): TabDonor[] {
  const donors: TabDonor[] = []
  for (const source of DONOR_SOURCES) {
    const gilPath = path.join(FIXTURES, source.snapshot)
    assert.ok(fs.existsSync(gilPath), `快照缺失: ${source.snapshot}`)
    const parsed = parseRoot9(new Uint8Array(fs.readFileSync(gilPath)))
    const record = parsed.recordsById.get(source.recordId)
    assert.ok(record, `记录 ${source.recordId} 不存在于 ${source.snapshot}`)
    assert.equal(record.kind, source.expectKind, `记录 ${source.recordId} kind=${record.kind}`)
    assert.equal(record.parentId, source.expectParent, 'parent 漂移')
    assert.equal(
      record.raw.length,
      source.expectLen,
      `记录 ${source.recordId} 长度 ${record.raw.length} != ${source.expectLen}` +
        '（先核对 references/ui-controls.md 对应轮结论，勿静默改长度）'
    )
    donors.push({
      id: source.id,
      sourceSnapshot: source.snapshot,
      selfId: source.recordId,
      parentId: record.parentId!,
      sha256: sha256(record.raw),
      hex: Buffer.from(record.raw).toString('hex')
    })
    console.log(
      `extracted ${source.id}: ${source.snapshot} record=${source.recordId}` +
        ` len=${record.raw.length} sha256=${donors[donors.length - 1].sha256.slice(0, 16)}...`
    )
  }
  return donors
}

function render(donors: TabDonor[]): string {
  const donorsLiteral = donors
    .map(
      (d) =>
        `  {\n` +
        `    id: '${d.id}',\n` +
        `    sourceSnapshot: '${d.sourceSnapshot}',\n` +
        `    selfId: ${d.selfId},\n` +
        `    parentId: ${d.parentId},\n` +
        `    sha256: '${d.sha256}',\n` +
        `    hex:\n` +
        `      '${d.hex}'\n` +
        `  }`
    )
    .join(',\n')
  return `/**
 * ui/src/tab-donors.ts — 页签命令的字节级 donor 注册表（票10）
 *
 * ⚠️ AUTO-GENERATED by \`npx tsx ui/tests/extract-tab-donors.ts\` —— 勿手改。
 * 字节来源 = 真实编辑器快照（.gsts/diff-exp/ui学习/）：
 *   - tab-create：轮29（悬浮页详情添加页签，1103B 全默认：单页面项
 *     页签项_1/页签文本 + 默认选择哨兵 + 空容器/控件状态块）
 * 候选装配 = 克隆 donor 字节 → 自身 ID/父引用重映射 → 宿主容器 f503 追加 + 簇末插入。
 * 字节级同步核验见 ui/tests/tab-assert.ts（轮28→29/29→30/35→36/36→38/38→46/65→66 重放）。
 */

export type TabDonorId = 'tab-create'

export interface TabDonor {
  id: TabDonorId
  /** 提取来源快照文件名（.gsts/diff-exp/ui学习/ 下，gitignored 本地留存） */
  sourceSnapshot: string
  selfId: number
  parentId: number
  /** 记录原始字节 sha256（hex 前核验防漂移） */
  sha256: string
  /** 记录原始字节 hex（= 编辑器该动作落盘的真实字节） */
  hex: string
}

/** 提取脚本覆写点（ui/tests/extract-tab-donors.ts 生成；空数组=占位态 fail-closed） */
export const TAB_DONORS: TabDonor[] = [
${donorsLiteral}
]

export function tabDonor(id: TabDonorId): TabDonor {
  const donor = TAB_DONORS.find((item) => item.id === id)
  if (!donor) {
    throw new Error(
      \`[error] tab donor 缺失（\${id}）：先运行 npx tsx ui/tests/extract-tab-donors.ts；\` +
        '缺失时禁止凭空猜字节（fail-closed）'
    )
  }
  return donor
}
`
}

const donors = extract()
assert.equal(donors.length, DONOR_SOURCES.length)
fs.writeFileSync(DONORS_FILE, render(donors))
console.log(`wrote ${DONORS_FILE}`)
console.log('next: npx tsx ui/tests/tab-assert.ts')
