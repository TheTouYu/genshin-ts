export interface UiDecodedName {
  /** 预设资产名，如 预设按钮_1 */
  presetName?: string
  /** 命中的预设名列表（一条记录可能含多个样式常量） */
  presetNames?: string[]
  /** 图片类型/标签/特效标签/特效名等 */
  semanticNames?: string[]
}

/** 返回单个数字命中的可读名；没有则 undefined */
export function lookupUiSemanticName(value: number): string | undefined {
  return (
    PRESET_NAME_BY_ID[value] ??
    IMAGE_TYPE_NAME_BY_ID[value] ??
    IMAGE_TAG_NAME_BY_ID[value] ??
    UI_EFFECT_CATEGORY_NAME_BY_ID[value] ??
    UI_EFFECT_TAG_NAME_BY_ID[value] ??
    UI_EFFECT_NAME_BY_ID[value]
  )
}

/** 从一批 varint 中收集已知语义名（保序去重） */
export function collectDecodedNames(varints: readonly number[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const value of varints) {
    const name = lookupUiSemanticName(value)
    if (name && !seen.has(name)) { seen.add(name); out.push(name) }
  }
  return out
}

/** 只收集预设资产名（30/31/32/33 段，避免小数字误命中图片/特效标签） */
export function collectPresetNames(varints: readonly number[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const value of varints) {
    const name = PRESET_NAME_BY_ID[value]
    if (name && !seen.has(name)) {
      seen.add(name)
      out.push(name)
    }
  }
  return out
}
